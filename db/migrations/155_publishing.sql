CREATE TABLE publishing_deliveries (
 id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
 campaign_id uuid NOT NULL DEFAULT gen_random_uuid(),
 channel_id text NOT NULL REFERENCES publishing_channels(id),
 conference_tag text NOT NULL DEFAULT '',
 source_ref text,
 title text NOT NULL DEFAULT '',
 body text NOT NULL DEFAULT '',
 reply text NOT NULL DEFAULT '',
 media jsonb NOT NULL DEFAULT '[]',
 mode text NOT NULL CHECK(mode IN ('draft','queue','fixed')),
 state text NOT NULL DEFAULT 'draft' CHECK(state IN ('draft','scheduled','sending','published','failed','needs_review','canceled')),
 scheduled_at timestamptz,
 queue_order bigint GENERATED BY DEFAULT AS IDENTITY,
 attempts integer NOT NULL DEFAULT 0,
 started_at timestamptz,
 lease_until timestamptz,
 root_id text NOT NULL DEFAULT '',
 published_url text NOT NULL DEFAULT '',
 error text NOT NULL DEFAULT '',
 version integer NOT NULL DEFAULT 1,
 created_at timestamptz NOT NULL DEFAULT now(),
 updated_at timestamptz NOT NULL DEFAULT now(),
 UNIQUE(channel_id,source_ref)
);
CREATE INDEX publishing_due ON publishing_deliveries(scheduled_at) WHERE state='scheduled';
CREATE TABLE publishing_external (
 provider text NOT NULL,
 remote_id text NOT NULL,
 channel_id text NOT NULL REFERENCES publishing_channels(id),
 conference_tag text NOT NULL DEFAULT '',
 title text NOT NULL,
 state text NOT NULL,
 starts_at timestamptz,
 ends_at timestamptz,
 url text NOT NULL DEFAULT '',
 updated_at timestamptz NOT NULL DEFAULT now(),
 PRIMARY KEY(provider,remote_id)
);
CREATE TABLE publishing_sync (
 provider text PRIMARY KEY,
 synced_at timestamptz NOT NULL
);
ALTER TABLE publishing_channels ADD COLUMN route_event_posts boolean NOT NULL DEFAULT false;
CREATE UNIQUE INDEX publishing_one_event_x ON publishing_channels(platform)
 WHERE route_event_posts AND platform='x' AND provider='direct';
